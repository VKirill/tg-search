// The OpenCode config the app owns (OPENCODE_CONFIG_DIR): providers with keys in 0600 files, our agents locked
// down to their own app tools, and the bridge plugin. Rewritten whenever providers or agents change; OpenCode
// watches the directory and reloads.
import { chmodSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const TOOL_PREFIX = 'tgs_';

export interface ProviderModel {
  id: string; // model id at the provider
  name: string;
  vision: boolean;
  tools: boolean;
  context: number;
  output: number;
  reasoning: string[]; // reasoning effort levels the provider accepts (variants)
}

export interface ProviderConfig {
  id: string; // providers.<id> — also the integration id for credentials
  name: string;
  // 'openai-compatible' — any /v1/chat/completions endpoint; 'catalog' — a provider OpenCode already knows
  // (openrouter, deepseek, zai-coding-plan…): only its key is needed
  kind: 'openai-compatible' | 'catalog';
  baseURL?: string;
  apiKey?: string; // written to secrets/<id>, never into opencode.json
  models?: ProviderModel[];
}

export interface AgentConfig {
  id: string; // tgs-<name>
  description: string;
  mode: 'primary' | 'subagent';
  system: string;
  steps?: number;
  tools: string[]; // app tool names (without prefix) this agent may call
}

const PLUGIN = `// Generated by TG Search — the bridge between OpenCode agents and the app's tools. Do not edit.
const url = process.env.TGS_BRIDGE_URL;
const token = process.env.TGS_BRIDGE_TOKEN;

async function bridge(path, body) {
  const res = await fetch(url + path, {
    method: body === undefined ? "GET" : "POST",
    headers: { Authorization: "Bearer " + token, "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  if (!res.ok) throw new Error("TG Search bridge: HTTP " + res.status + " " + text.slice(0, 300));
  return JSON.parse(text);
}

export default {
  id: "tgsearch-bridge",
  setup: async (ctx) => {
    if (!url || !token) return;
    const { tools } = await bridge("/tools");
    await ctx.tool.transform((editor) => {
      for (const t of tools) {
        editor.add({
          name: t.name,
          description: t.description,
          input: t.input,
          options: { codemode: false },
          execute: async (input, context) => {
            const out = await bridge("/call", { tool: t.name, input, sessionID: context.sessionID, agent: context.agent, callID: context.id });
            return { content: out.content };
          },
        });
      }
    });
  },
};
`;

export function writeOpencodeConfig(dir: string, providers: ProviderConfig[], agents: AgentConfig[], defaultModel?: { providerID: string; id: string }) {
  mkdirSync(join(dir, 'plugins'), { recursive: true });
  const secrets = join(dir, 'secrets');
  rmSync(secrets, { recursive: true, force: true });
  mkdirSync(secrets, { recursive: true });
  chmodSync(secrets, 0o700);

  const providersOut: Record<string, unknown> = {};
  for (const p of providers) {
    const settings: Record<string, string> = {};
    if (p.apiKey) {
      writeFileSync(join(secrets, p.id), p.apiKey, { mode: 0o600 });
      settings.apiKey = `{file:./secrets/${p.id}}`;
    }
    if (p.kind === 'catalog') {
      if (Object.keys(settings).length) providersOut[p.id] = { settings };
      continue;
    }
    providersOut[p.id] = {
      name: p.name,
      package: 'aisdk:@ai-sdk/openai-compatible',
      settings: { ...settings, baseURL: p.baseURL },
      models: Object.fromEntries((p.models ?? []).map((m) => [m.id, {
        name: m.name,
        capabilities: { tools: m.tools, input: m.vision ? ['text', 'image'] : ['text'], output: ['text'] },
        limit: { context: m.context, output: m.output },
        ...(m.reasoning.length ? { variants: m.reasoning.map((e) => ({ id: e, settings: { reasoningEffort: e } })) } : {}),
      }])),
    };
  }

  const agentsOut = Object.fromEntries(agents.map((a) => [a.id, {
    description: a.description,
    mode: a.mode,
    system: a.system,
    ...(a.steps ? { steps: a.steps } : {}),
    // last match wins: everything (shell, files, web, subagents…) denied, then only this agent's app tools
    permissions: [
      { action: '*', resource: '*', effect: 'deny' },
      ...a.tools.map((t) => ({ action: `${TOOL_PREFIX}${t}`, resource: '*', effect: 'allow' })),
    ],
  }]));

  const config = {
    $schema: 'https://opencode.ai/config.json',
    ...(defaultModel ? { model: `${defaultModel.providerID}/${defaultModel.id}` } : {}),
    plugins: ['./plugins/tgsearch.js'],
    websearch: false,
    providers: providersOut,
    agents: agentsOut,
  };
  writeFileSync(join(dir, 'opencode.json'), JSON.stringify(config, null, 2));
  writeFileSync(join(dir, 'plugins', 'tgsearch.js'), PLUGIN);
}
