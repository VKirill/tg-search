#!/usr/bin/env node
// Writes the skill's API reference from the app's contracts (src/shared/types.ts): references/api.md — every method of
// the control API with its parameters and comments; references/types.md — all the types. Run after changing contracts:
// npm run skill:refs (a test fails when the reference is stale).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const types = readFileSync(join(ROOT, 'src/shared/types.ts'), 'utf8');

export function apiBlock(src) {
  const start = src.indexOf('export interface Api {');
  if (start < 0) throw new Error('interface Api not found');
  let depth = 0;
  for (let i = src.indexOf('{', start); i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(start, i + 1);
  }
  throw new Error('interface Api is not closed');
}

export function renderApi(src) {
  return [
    '# TG Search — API',
    '',
    '<!-- generated by scripts/gen-skill-refs.mjs from src/shared/types.ts — do not edit -->',
    '',
    'Каждый метод вызывается как `раздел.метод` с массивом аргументов по порядку: в MCP — инструмент `call`',
    '(`{"method": "helper.chats", "args": []}`), в CLI — `tgs call helper.chats`, по HTTP — `POST /api/helper.chats` с телом `{"args": []}`.',
    'Типы параметров и результатов — в [types.md](types.md). `onEvent` в API нет: события — инструмент `events` или `tgs events`.',
    '',
    '```ts',
    apiBlock(src),
    '```',
    '',
  ].join('\n');
}

export function renderTypes(src) {
  return ['# TG Search — типы', '', '<!-- generated by scripts/gen-skill-refs.mjs from src/shared/types.ts — do not edit -->', '', '```ts', src.trim(), '```', ''].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = join(ROOT, 'skills/tg-search/references');
  writeFileSync(join(dir, 'api.md'), renderApi(types));
  writeFileSync(join(dir, 'types.md'), renderTypes(types));
  console.log('skills/tg-search/references: api.md, types.md');
}
